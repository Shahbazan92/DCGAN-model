# 3. Define the DCGAN Architecture
latent_dim = 100
features_g = 64
features_d = 64

class Generator(nn.Module):
    def __init__(self):
        super(Generator, self).__init__()
        self.net = nn.Sequential(
            # Input: latent vector Z of size latent_dim
            nn.ConvTranspose2d(latent_dim, features_g * 8, 4, 1, 0, bias=False),
            nn.BatchNorm2d(features_g * 8),
            nn.ReLU(True),
            # State size: (features_g*8) x 4 x 4
            nn.ConvTranspose2d(features_g * 8, features_g * 4, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_g * 4),
            nn.ReLU(True),
            # State size: (features_g*4) x 8 x 8
            nn.ConvTranspose2d(features_g * 4, features_g * 2, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_g * 2),
            nn.ReLU(True),
            # State size: (features_g*2) x 16 x 16
            nn.ConvTranspose2d(features_g * 2, features_g, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_g),
            nn.ReLU(True),
            # State size: (features_g) x 32 x 32
            nn.ConvTranspose2d(features_g, 3, 4, 2, 1, bias=False),
            nn.Tanh()
            # Output state size: 3 x 64 x 64
        )

    def forward(self, x):
        return self.net(x)

class Discriminator(nn.Module):
    def __init__(self):
        super(Discriminator, self).__init__()
        self.net = nn.Sequential(
            # Input state size: 3 x 64 x 64
            nn.Conv2d(3, features_d, 4, 2, 1, bias=False),
            nn.LeakyReLU(0.2, inplace=True),
            # State size: (features_d) x 32 x 32
            nn.Conv2d(features_d, features_d * 2, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_d * 2),
            nn.LeakyReLU(0.2, inplace=True),
            # State size: (features_d*2) x 16 x 16
            nn.Conv2d(features_d * 2, features_d * 4, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_d * 4),
            nn.LeakyReLU(0.2, inplace=True),
            # State size: (features_d*4) x 8 x 8
            nn.Conv2d(features_d * 4, features_d * 8, 4, 2, 1, bias=False),
            nn.BatchNorm2d(features_d * 8),
            nn.LeakyReLU(0.2, inplace=True),
            # State size: (features_d*8) x 4 x 4
            nn.Conv2d(features_d * 8, 1, 4, 1, 0, bias=False),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.net(x).view(-1, 1)

# 4. Model Training & Discriminator Accuracy Evaluation Setup
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
netG = Generator().to(device)
netD = Discriminator().to(device)

criterion = nn.BCELoss()
optimizerD = optim.Adam(netD.parameters(), lr=0.0002, betas=(0.5, 0.999))
optimizerG = optim.Adam(netG.parameters(), lr=0.0002, betas=(0.5, 0.999))

num_epochs = 50
print(f"Training starting on device: {device}")

for epoch in range(num_epochs):
    for i, real_images in enumerate(train_loader):
        real_images = real_images.to(device)
        b_size = real_images.size(0)

        # Train Discriminator with real images
        netD.zero_grad()
        label_real = torch.full((b_size, 1), 1.0, dtype=torch.float, device=device)
        output_real = netD(real_images)
        lossD_real = criterion(output_real, label_real)
        lossD_real.backward()

        # Train Discriminator with fake images
        noise = torch.randn(b_size, latent_dim, 1, 1, device=device)
        fake_images = netG(noise)
        label_fake = torch.full((b_size, 1), 0.0, dtype=torch.float, device=device)
        output_fake = netD(fake_images.detach())
        lossD_fake = criterion(output_fake, label_fake)
        lossD_fake.backward()
        optimizerD.step()

        # Train Generator
        netG.zero_grad()
        label_gen = torch.full((b_size, 1), 1.0, dtype=torch.float, device=device) # Generator wants fake images to be classified as real
        output_g = netD(fake_images)
        lossG = criterion(output_g, label_gen)
        lossG.backward()
        optimizerG.step()

    if (epoch + 1) % 10 == 0 or epoch == 0:
        print(f"Epoch [{epoch+1}/{num_epochs}] | Loss D: {lossD_real.item()+lossD_fake.item():.4f} | Loss G: {lossG.item():.4f}")

