import tensorflow as tf
from tensorflow.keras import layers, models
import os

# Define the equivalent DCGAN Generator in Keras
def build_generator(latent_dim=100, features_g=64):
    model = models.Sequential([
        # Input: latent vector Z of shape (latent_dim,)
        layers.Input(shape=(latent_dim,)),
        layers.Reshape((1, 1, latent_dim)),

        # State size: (features_g*8) x 4 x 4
        layers.Conv2DTranspose(features_g * 8, kernel_size=4, strides=1, padding='valid', use_bias=False),
        layers.BatchNormalization(),
        layers.ReLU(),

        # State size: (features_g*4) x 8 x 8
        layers.Conv2DTranspose(features_g * 4, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.ReLU(),

        # State size: (features_g*2) x 16 x 16
        layers.Conv2DTranspose(features_g * 2, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.ReLU(),

        # State size: (features_g) x 32 x 32
        layers.Conv2DTranspose(features_g, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.ReLU(),

        # Output state size: 3 x 64 x 64
        layers.Conv2DTranspose(3, kernel_size=4, strides=2, padding='same', use_bias=False, activation='tanh')
    ])
    return model

# Define the equivalent DCGAN Discriminator in Keras
def build_discriminator(features_d=64):
    model = models.Sequential([
        layers.Input(shape=(64, 64, 3)),

        # State size: (features_d) x 32 x 32
        layers.Conv2D(features_d, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.LeakyReLU(negative_slope=0.2),

        # State size: (features_d*2) x 16 x 16
        layers.Conv2D(features_d * 2, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.LeakyReLU(negative_slope=0.2),

        # State size: (features_d*4) x 8 x 8
        layers.Conv2D(features_d * 4, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.LeakyReLU(negative_slope=0.2),

        # State size: (features_d*8) x 4 x 4
        layers.Conv2D(features_d * 8, kernel_size=4, strides=2, padding='same', use_bias=False),
        layers.BatchNormalization(),
        layers.LeakyReLU(negative_slope=0.2),

        # Output probability score
        layers.Conv2D(1, kernel_size=4, strides=1, padding='valid', use_bias=False),
        layers.Flatten(),
        layers.Activation('sigmoid')
    ])
    return model

